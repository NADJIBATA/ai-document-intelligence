import type {
  Comparison,
  ComparisonSide,
  ComparisonSource,
  PassageRef,
  Significance,
} from "../../api/types";
import { humanize, pageLabel } from "../../lib/format";
import { Badge, type BadgeTone } from "../ui/Badge";
import { Card, CardHeader } from "../ui/Card";
import { EmptyState } from "../ui/EmptyState";
import { CheckIcon } from "../ui/Icons";

interface ComparisonViewProps {
  comparison: Comparison;
  onOpenPassage: (passage: PassageRef) => void;
}

const SIGNIFICANCE: Record<Significance, { label: string; tone: BadgeTone }> = {
  high: { label: "High impact", tone: "red" },
  medium: { label: "Medium impact", tone: "amber" },
  low: { label: "Low impact", tone: "neutral" },
};

function SourceChips({
  sources,
  onOpenPassage,
}: {
  sources: ComparisonSource[];
  onOpenPassage: (passage: PassageRef) => void;
}) {
  if (sources.length === 0) {
    return null;
  }
  return (
    <div className="mt-2 flex flex-wrap gap-1.5">
      {sources.map((source) => (
        <button
          key={source.ref}
          type="button"
          onClick={() => onOpenPassage(source)}
          className="inline-flex items-center gap-1 rounded-md border border-slate-200 bg-white px-2 py-0.5 text-xs text-slate-600 hover:border-brand-300 hover:text-brand-700"
          title={source.excerpt}
        >
          <span className="font-semibold">{source.ref}</span>
          {pageLabel(source.page) ?? "Passage"}
        </button>
      ))}
    </div>
  );
}

function Side({
  name,
  side,
  onOpenPassage,
}: {
  name: string;
  side: ComparisonSide;
  onOpenPassage: (passage: PassageRef) => void;
}) {
  return (
    <div className="min-w-0 rounded-lg bg-slate-50 p-3">
      <p className="truncate text-xs font-semibold uppercase tracking-wide text-slate-500" title={name}>
        {name}
      </p>
      {side.value ? (
        <p className="mt-1 whitespace-pre-wrap text-sm text-slate-800">{side.value}</p>
      ) : (
        <p className="mt-1 text-sm italic text-slate-400">Not addressed in this document.</p>
      )}
      <SourceChips sources={side.sources} onOpenPassage={onOpenPassage} />
    </div>
  );
}

export function ComparisonView({ comparison, onOpenPassage }: ComparisonViewProps) {
  const result = comparison.result;
  if (result === null) {
    return null;
  }
  return (
    <div className="space-y-6">
      <Card>
        <CardHeader title="Summary" />
        <p className="whitespace-pre-wrap px-5 py-4 text-sm leading-relaxed text-slate-700">
          {result.summary || "No summary was produced."}
        </p>
      </Card>

      <Card>
        <CardHeader
          title="Main differences"
          description={`${result.differences.length} difference${
            result.differences.length === 1 ? "" : "s"
          } supported by passages of the documents`}
        />
        {result.differences.length === 0 ? (
          <EmptyState
            icon={<CheckIcon />}
            title="No significant difference found"
            description="The passages compared do not differ on the selected aspects."
          />
        ) : (
          <ul className="divide-y divide-slate-100">
            {result.differences.map((difference, index) => (
              <li key={`${difference.title}-${index}`} className="px-5 py-4">
                <div className="mb-3 flex flex-wrap items-center gap-2">
                  <h3 className="text-sm font-semibold text-slate-900">{difference.title}</h3>
                  <Badge tone="blue">{humanize(difference.aspect)}</Badge>
                  <Badge tone={SIGNIFICANCE[difference.significance].tone}>
                    {SIGNIFICANCE[difference.significance].label}
                  </Badge>
                </div>
                <div className="grid gap-3 md:grid-cols-2">
                  <Side
                    name={comparison.document_a.name}
                    side={difference.document_a}
                    onOpenPassage={onOpenPassage}
                  />
                  <Side
                    name={comparison.document_b.name}
                    side={difference.document_b}
                    onOpenPassage={onOpenPassage}
                  />
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>

      {result.similarities.length > 0 ? (
        <Card>
          <CardHeader title="Similarities" />
          <ul className="list-disc space-y-1.5 px-5 py-4 pl-10 text-sm text-slate-700">
            {result.similarities.map((similarity) => (
              <li key={similarity}>{similarity}</li>
            ))}
          </ul>
        </Card>
      ) : null}

      <p className="text-xs text-slate-400">
        {result.model ? `Generated by ${result.model}. ` : ""}Generated by AI: check important
        differences against the documents.
      </p>
    </div>
  );
}
